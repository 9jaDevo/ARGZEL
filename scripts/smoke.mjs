// Post-deploy smoke test: auth, confirmation guard, voice parse (Gemma), save,
// fetch, edit, delete, cron auth and rate limiting. Sends no email.
// Usage: BASE=https://your-app.onrender.com [CRON_SECRET_PROD=...] npm run smoke
// Each run leaves one throwaway account (smoke-<timestamp>@example.com); its reminder is deleted.
import { randomBytes } from 'node:crypto';

const B = (process.env.BASE || 'http://localhost:3000').replace(/\/+$/, '');
const local = /^http:\/\/(localhost|127\.0\.0\.1)/.test(B);
if (local) {
  try {
    process.loadEnvFile('.env.local');
  } catch {
    // Optional: only needed for the cron check.
  }
}
// The cron check runs only with the target's own secret (production's is generated by Render).
const CRON = local ? process.env.CRON_SECRET : process.env.CRON_SECRET_PROD;
let cookie = '', fails = 0;
const ok = (label, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'}  ${label}${!cond && extra ? ' -> ' + extra : ''}`); if (!cond) fails++; };
async function call(method, path, body, headers = {}) {
  const res = await fetch(B + path, { method, headers: { ...(body && { 'content-type': 'application/json' }), ...(cookie && { cookie }), ...headers }, body: body && JSON.stringify(body) });
  const sc = res.headers.get('set-cookie'); if (sc) cookie = sc.split(';')[0].endsWith('=') ? '' : sc.split(';')[0];
  let data; try { data = await res.json(); } catch { data = null; }
  return { status: res.status, data, setCookie: sc };
}
const email = `smoke-${Date.now()}@example.com`, password = randomBytes(12).toString('base64url');
let r = await call('GET', '/api/health'); ok('health: db up', r.status === 200 && r.data.db === 'up', JSON.stringify(r.data));
r = await call('GET', '/'); ok('home page renders', r.status === 200 || r.data === null);
r = await call('GET', '/api/me'); ok('me without session -> 401', r.status === 401);
r = await call('POST', '/api/auth/signup', { name: 'E2E Test', email, password, timezone: 'Africa/Lagos' }); ok('signup -> 201', r.status === 201, JSON.stringify(r.data));
ok('session cookie Secure + HttpOnly in production', /HttpOnly/i.test(r.setCookie || '') && /Secure/i.test(r.setCookie || ''), r.setCookie);
r = await call('POST', '/api/auth/signout'); ok('signout -> 200', r.status === 200);
r = await call('POST', '/api/auth/signin', { email, password }); ok('signin -> 200', r.status === 200, JSON.stringify(r.data));
r = await call('GET', '/api/me'); ok('me -> own profile', r.status === 200 && r.data.user.email === email);
const when = new Date(Date.now() + 3 * 864e5).toISOString();
r = await call('POST', '/api/reminders', { title: 'Unconfirmed', timezone: 'Africa/Lagos', scheduled_at: when }); ok('save without confirmed -> 400', r.status === 400 && r.data.error.fields.confirmed);
const t0 = Date.now();
r = await call('POST', '/api/voice/parse', { text: 'Every Monday at 7 AM remind me to pray.' });
ok(`voice parse via Gemma (${Date.now() - t0} ms)`, r.status === 200 && r.data.result.recurrence === 'weekly' && r.data.result.time === '07:00' && !r.data.result.needs_clarification, JSON.stringify(r.data).slice(0, 300));
const p = r.data?.result;
r = await call('POST', '/api/reminders', { confirmed: true, title: p?.title ?? 'Pray', notes: p?.notes ?? '', source_text: p?.source_text ?? '', timezone: 'Africa/Lagos', recurrence: 'weekly', scheduled_at: p?.scheduled_at ?? when, ai_confidence: p?.confidence ?? null });
ok('save confirmed parsed reminder -> 201', r.status === 201 && r.data.reminder.status === 'scheduled', JSON.stringify(r.data));
const id = r.data?.reminder?.id;
r = await call('GET', '/api/reminders'); ok('fetch reminders -> 1', r.status === 200 && r.data.reminders.length === 1 && r.data.reminders[0].id === id);
r = await call('PATCH', `/api/reminders/${id}`, { title: 'Morning prayer' }); ok('edit -> 200', r.status === 200 && r.data.reminder.title === 'Morning prayer');
r = await call('POST', '/api/cron/dispatch', undefined, { authorization: 'Bearer wrong-secret-0000000' }); ok('cron with wrong secret -> 401', r.status === 401);
if (CRON) { r = await call('POST', '/api/cron/dispatch', undefined, { authorization: `Bearer ${CRON}` }); ok('cron with secret -> 200, nothing due', r.status === 200 && r.data.summary.claimed === 0, JSON.stringify(r.data)); }
r = await call('DELETE', `/api/reminders/${id}`); ok('delete -> 200', r.status === 200);
let last;
for (let i = 0; i < 11; i++) last = await call('POST', '/api/auth/signin', { email, password: 'wrong-password-x' });
ok('11th wrong sign-in for one account -> 429', last.status === 429 && last.data.error.code === 'RATE_LIMITED', JSON.stringify(last.data));
console.log(`Smoke account: ${email}`);
console.log(fails ? `\n${fails} FAILED` : '\nALL PASSED');
process.exit(fails ? 1 : 0);
